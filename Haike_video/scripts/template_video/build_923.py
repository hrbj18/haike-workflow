def ctext(d, y, text, f, fill, stroke=None, stroke_w=0):
    b = d.textbbox((0, 0), text, font=f, stroke_width=stroke_w)
    w = b[2] - b[0]
    ink = b[3] - b[1]
    x = (W - w) // 2
    d.text((x, y - b[1]), text, font=f, fill=fill, stroke_fill=stroke, stroke_width=stroke_w)
    return y + ink + int(f.size * 0.18)


def make_top(path: str, lines, bar: str) -> None:
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    # Fully cover source titles/subtitles in the upper band before drawing ours.
    # 先量布局，再决定底板高度：底板必须完整盖住结论条，
    # 否则结论条下沿会露出一条未覆盖的透明缝（v1 为 32px 隐患，实测证实）。
    y = TOP_SAFE
    for text, _f, _s, sw in lines:
        b = d.textbbox((0, 0), text, font=F_TOP, stroke_width=sw)
        y += (b[3] - b[1]) + int(F_TOP.size * 0.18)
    plate_bottom = max(TOP_PLATE_BOTTOM, y + GAP_BEFORE_BAR + BAR_H)

    d.rectangle((0, 0, W, plate_bottom), fill=PLATE_COLOR)
    y = TOP_SAFE
    for text, fill, stroke, sw in lines:
        y = ctext(d, y, text, F_TOP, fill, stroke, sw)
    y += GAP_BEFORE_BAR
    # Keep the text bar opaque so source UI cannot show through it.
    d.rounded_rectangle((BAR_X0, y, BAR_X1, y + BAR_H), radius=14, fill=(0, 0, 0, 255))
    b = d.textbbox((0, 0), bar, font=F_BAR, stroke_width=4)
    tw = b[2] - b[0]
    d.text(((W - tw) // 2, y + (BAR_H - (b[3] - b[1])) // 2 - b[1]),
           bar, font=F_BAR, fill=YELLOW, stroke_fill=(255, 255, 255, 255), stroke_width=4)
    img.save(path)


def make_detail(path: str, lines) -> None:
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    # Fully cover source captions and platform UI in the lower band.
    d.rectangle((0, BOTTOM_PLATE_TOP, W, H), fill=PLATE_COLOR)
    lh = 82
    block_h = lh * len(lines) + 56
    bottom = 1660  # 抖音安全区 86.5%
    y0 = bottom - block_h
    # Keep the detail card opaque so source captions cannot show through it.
    d.rounded_rectangle((CARD_X0, y0, CARD_X1, bottom), radius=18, fill=(0, 0, 0, 255))
    y = y0 + 28
    for text, fill in lines:
        y = ctext(d, y, text, F_DET, fill)
    img.save(path)


def build(key: str) -> str:
    spec = SPECS[key]
    os.makedirs(OUT, exist_ok=True)
    top_png = os.path.join(OUT, f"{key}_top.png")
    make_top(top_png, spec["top"], spec["bar"])
    det_pngs = []
    for i, lines in enumerate(spec["details"], 1):
        p = os.path.join(OUT, f"{key}_det{i}.png")
        make_detail(p, lines)
        det_pngs.append(p)

    scenes = [(raw(f"{key}_1.mp4"), 0.0, 3.0),
              (raw(f"{key}_2.mp4"), 0.0, 3.0),
              (raw(f"{key}_3.mp4"), 0.0, 3.0)]
    for f, _, _ in scenes:
        assert os.path.isfile(f), f"missing broll: {f}"
    total = sum(s[2] for s in scenes)
    cuts = []
    t = 0.0
    for _, _, dur in scenes[:-1]:
        t += dur
        cuts.append(round(t, 2))

    inputs = []
    for f, ss, dur in scenes:
        inputs += ["-ss", str(ss), "-t", str(dur), "-i", f]
    inputs += ["-i", top_png]
    for p in det_pngs:
        inputs += ["-i", p]
    inputs += ["-i", spec["bgm"]]
    i_top = len(scenes)
    i_bgm = i_top + 1 + len(det_pngs)

    scale = ("scale=1080:1920:force_original_aspect_ratio=increase,"
             "crop=1080:1920,setsar=1,fps=30")
    fc = []
    for i in range(len(scenes)):
        fc.append(f"[{i}:v]{scale}[v{i}]")
    fc.append("".join(f"[v{i}]" for i in range(len(scenes)))
              + f"concat=n={len(scenes)}:v=1:a=0[bg]")
    fc.append(f"[bg][{i_top}:v]overlay=0:0[cur]")
    prev = "cur"
    bounds = cuts + [total]
    for j, p in enumerate(det_pngs):
        lo = 0.0 if j == 0 else cuts[j - 1]
        hi = bounds[j]
        tag = f"d{j}"
        fc.append(f"[{prev}][{i_top + 1 + j}:v]overlay=0:0:enable='between(t,{lo},{hi})'[{tag}]")
        prev = tag

    target = spec.get("lufs_target", -11)
    if spec.get("loud_mode") == "limit":
        # BGM 峰值余量不足时 loudnorm 会被 TP 卡死，改用增益+限制器硬拉响度
        boost = spec.get("boost_db", 16)
        af = (f"atrim=0:{total},afade=t=out:st={total - 1.2}:d=1.2,"
              f"volume={boost}dB,alimiter=limit=0.794:attack=1:release=80:level=disabled")
    else:
        af = (f"atrim=0:{total},afade=t=out:st={total - 1.2}:d=1.2,"
              f"loudnorm=I={target}:TP=-1.5:LRA=11")
    out = os.path.join(OUT, f"{key}_9s.mp4")
    cmd = ["ffmpeg", "-y", "-loglevel", "error"] + inputs + [
        "-filter_complex", ";".join(fc),
        "-map", f"[{prev}]", "-map", f"{i_bgm}:a",
        "-t", str(total),
        "-c:v", "libx264", "-crf", "19", "-preset", "medium", "-pix_fmt", "yuv420p",
        "-af", af, "-c:a", "aac", "-b:a", "192k",
        out,
    ]
    subprocess.run(cmd, check=True)
    print("OK:", out)
    return out


def main() -> int:
    arg = sys.argv[1] if len(sys.argv) > 1 else "all"
    keys = list(SPECS) if arg == "all" else [arg]
    for k in keys:
        build(k)
    return 0


